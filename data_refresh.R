# Headless Chrome needs --no-sandbox in containerized environments, where
# chromote's automatic Docker/CI detection doesn't always add it.
chromote::set_chrome_args(unique(c(chromote::get_chrome_args(), "--no-sandbox")))

refresh_dataset <- function(name, fetch, write) {
  message("Refreshing ", name, "...")
  tryCatch(
    {
      value <- fetch()
      write(value)
      log_refresh(name, "success", n_rows = NROW(value))
      message("  OK (", NROW(value), " rows)")
      TRUE
    },
    error = function(e) {
      log_refresh(name, "failure", message = conditionMessage(e))
      message("  FAILED - keeping previous cache: ", conditionMessage(e))
      FALSE
    }
  )
}

# NET INFLOWS (scraped from okanaganwatersupply.com) -----------------------
fetch_inflow <- function() {
  url <- "https://okanaganwatersupply.com/"
  session <- read_html_live(url)
  on.exit(try(session$session$close(), silent = TRUE), add = TRUE)

  cs <- session$session

  # Locate the "Data table" tab by its link text rather than a hardcoded
  # tab id (e.g. "tab-1288-3"), since that id is generated by bslib and
  # could change if the site is redeployed.
  find_tab_js <- "
  (function() {
    var links = Array.from(document.querySelectorAll('a.nav-link'));
    var target = links.find(function(a) {
      return a.textContent.trim() === 'Data table';
    });
    return target ? target.getAttribute('href') : null;
  })();
  "
  tab_href <- cs$Runtime$evaluate(find_tab_js, returnByValue = TRUE)$result$value
  if (is.null(tab_href)) {
    stop('Could not find a nav-link with text "Data table" on the page.')
  }

  # Shiny suspends rendering of hidden-tab outputs, and a plain click on
  # the tab link doesn't reliably fire Bootstrap's shown.bs.tab event
  # inside chromote, so trigger it directly via the Bootstrap Tab API.
  show_tab_js <- sprintf("
  (function() {
    var el = document.querySelector(\"a.nav-link[href='%s']\");
    if (!el) return false;
    new bootstrap.Tab(el).show();
    return true;
  })();
  ", tab_href)
  shown <- cs$Runtime$evaluate(show_tab_js, returnByValue = TRUE)$result$value
  if (!isTRUE(shown)) {
    stop("Found the tab href but could not activate it: ", tab_href)
  }

  Sys.sleep(2) # allow Shiny to render the table

  tbl_node <- session$html_elements(paste0(tab_href, " table"))
  if (length(tbl_node) == 0) {
    stop("Data table tab was activated but no <table> was found inside it.")
  }

  html_table(tbl_node[[1]]) |>
    setNames(c("Week ending", "Current (ac-ft)", "1944-2025 avg (ac-ft)", "% of average"))
}

refresh_dataset(
  "df_inflow",
  fetch_inflow,
  function(df) atomic_write_csv(df, file.path(CACHE_DIR, "df_inflow.csv"))
)

