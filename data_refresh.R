# OKANAGAN LAKE DAILY MEAN LEVEL (weather.gc.ca API, paginated) -------------
refresh_dataset(
  "df_daily_mean",
  function() {
    limit <- 10000
    offset <- 0
    all_data <- list()
    repeat {
      url <- paste0(
        "https://api.weather.gc.ca/collections/hydrometric-daily-mean/items?",
        "f=csv",
        "&STATION_NUMBER=08NM083",
        "&datetime=1990-01-01/..",
        "&properties=IDENTIFIER,DATE,LEVEL",
        "&offset=", offset,
        "&limit=", limit
      )
      df_d <- read_csv(url, show_col_types = FALSE)
      if (nrow(df_d) == 0) break
      all_data[[length(all_data) + 1]] <- df_d
      if (nrow(df_d) < limit) break
      offset <- offset + limit
    }
    bind_rows(all_data) |>
      mutate(
        Year = year(DATE),
        Month = month(DATE),
        Day = day(DATE),
        DayOfYear = yday(DATE)
      )
  },
  function(df) atomic_write_csv(df, file.path(CACHE_DIR, "df_daily_mean.csv"))
)

